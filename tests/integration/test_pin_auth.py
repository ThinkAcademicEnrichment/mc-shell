import os
import re
import time
import unittest
from unittest.mock import patch

# Set environment variable before server starts so RemoteSession enables headless test mode
os.environ["MCSHELL_TEST_MODE"] = "1"

from tests.integration.base_magic import BaseMagicTest
from tests.config import TEST_PLAYER_NAME
from mcshell.constants import MC_WORLDS_BASE_DIR
from mcshell.mcjuice import MCJuiceClient

class PinAuthUnitTest(BaseMagicTest):
    """
    Headless integration test for the Java RemoteSession <-> Python MCJuiceClient
    4-digit PIN and Host Secret authentication state machine.
    """

    def setUp(self):
        # Always start each test with a clean token cache
        MCJuiceClient._SESSION_TOKENS.clear()
        self.mj_host = "127.0.0.1"
        self.mj_port = self.mcshell.local_server.mj_port
        self.log_file = MC_WORLDS_BASE_DIR / self.world_name / "logs" / "latest.log"

    def _scrape_latest_pin_from_log(self, player_name: str, timeout: float = 5.0) -> str:
        """
        Reads PaperMC's logs/latest.log to find the most recent 4-digit PIN
        generated by RemoteSession.requestPin() for `player_name`.
        """
        # Safely escape the brackets and use string concatenation to avoid f-string quirks
        pattern = re.compile(r"\[MC-ED-AUTH\] Generated PIN for " + re.escape(player_name) + r": (\d{4})")
        
        deadline = time.time() + timeout
        while time.time() < deadline:
            if self.log_file.exists():
                content = self.log_file.read_text(encoding="utf-8", errors="ignore")
                matches = pattern.findall(content)
                if matches:
                    return matches[-1]  # Return the most recently logged PIN
            time.sleep(0.2)
        raise AssertionError(f"Could not find generated PIN for {player_name} in {self.log_file}")

    def test_01_wrong_pin_rejected_by_java(self):
        """Entering an incorrect 4-digit PIN must raise PermissionError and leave cache empty."""
        with patch("rich.prompt.Prompt.ask", return_value="0000"):
            # Even in the 1-in-10,000 chance the PIN is 0000, we can check a non-4-digit string like '99999'
            pass

        with patch("rich.prompt.Prompt.ask", return_value="BAD_PIN"):
            with self.assertRaises(PermissionError):
                MCJuiceClient.create(
                    address=self.mj_host,
                    port=self.mj_port,
                    playerName=TEST_PLAYER_NAME
                )

        # Ensure no session token was cached
        key = (self.mj_host, self.mj_port, TEST_PLAYER_NAME.lower())
        self.assertNotIn(key, MCJuiceClient._SESSION_TOKENS)

    def test_02_valid_pin_scraped_from_server_log_authenticates_and_caches(self):
        """
        Simulates a console user: when Prompt.ask is called, we scrape the real 4-digit PIN
        from the PaperMC server log, return it, and verify the socket is authenticated.
        """
        def auto_pin_responder(prompt_text, *args, **kwargs):
            pin = self._scrape_latest_pin_from_log(TEST_PLAYER_NAME)
            print(f"[TEST] Scraped live PIN from latest.log: {pin}")
            return pin

        with patch("rich.prompt.Prompt.ask", side_effect=auto_pin_responder) as mock_prompt:
            client = MCJuiceClient.create(
                address=self.mj_host,
                port=self.mj_port,
                playerName=TEST_PLAYER_NAME
            )
            mock_prompt.assert_called_once()

        try:
            # In headless test mode without a 3D client, resumeSession returns -999
            self.assertEqual(client.entity_id, -999)

            # Verify the UUID token was stored in _SESSION_TOKENS
            key = (self.mj_host, self.mj_port, TEST_PLAYER_NAME.lower())
            self.assertIn(key, MCJuiceClient._SESSION_TOKENS)
            cached_token = MCJuiceClient._SESSION_TOKENS[key]
            self.assertTrue(len(cached_token) > 10)

            # A second client creation must reuse the cached token WITHOUT calling Prompt.ask!
            with patch("rich.prompt.Prompt.ask") as mock_prompt_second:
                client2 = MCJuiceClient.create(
                    address=self.mj_host,
                    port=self.mj_port,
                    playerName=TEST_PLAYER_NAME
                )
                mock_prompt_second.assert_not_called()
                self.assertEqual(client2.entity_id, -999)
                client2.conn.close()
                client2.event_conn.close()
        finally:
            client.conn.close()
            client.event_conn.close()

    def test_03_host_secret_auto_authentication(self):
        """
        Tests the authenticateHost path using the RCON password from server.properties.
        """
        raw_client = MCJuiceClient.create(address=self.mj_host, port=self.mj_port, playerName="")
        try:
            # 1. Wrong RCON password must return 'INVALID'
            bad_token = raw_client.admin.authenticateHost(TEST_PLAYER_NAME, "wrong_password")
            self.assertEqual(bad_token, "INVALID")

            # 2. Read the real RCON password from the test world's server.properties
            props_path = MC_WORLDS_BASE_DIR / self.world_name / "server.properties"
            rcon_pass = "password" # Fallback
            if props_path.exists():
                for line in props_path.read_text().splitlines():
                    if line.startswith("rcon.password="):
                        rcon_pass = line.split("=", 1)[1].strip()
                        break

            self.assertIsNotNone(rcon_pass, "rcon.password not found in server.properties")

            # 3. Valid RCON password must return a valid session token and allow resumeSession
            valid_token = raw_client.admin.authenticateHost(TEST_PLAYER_NAME, rcon_pass)
            self.assertNotEqual(valid_token, "INVALID")

            eid = raw_client.admin.resumeSession(TEST_PLAYER_NAME, valid_token)
            self.assertEqual(eid, -999)
        finally:
            raw_client.conn.close()
            raw_client.event_conn.close()


if __name__ == "__main__":
    unittest.main()